"""
Where rider documents are kept: S3 in production, a local folder in
development (see settings.document_storage). Callers encrypt before put()
and decrypt after get(); this module only moves bytes.
"""
import logging
from pathlib import Path

import boto3
from botocore.exceptions import BotoCoreError, ClientError

from app.core.config import settings

log = logging.getLogger("alphabet.core.document_store")


class DocumentStoreError(Exception):
    """The document could not be stored or fetched."""


def _local_path(key: str) -> Path:
    root = Path(settings.LOCAL_DOCUMENTS_DIR).resolve()
    path = (root / key).resolve()
    # Keys are generated by the server, but never let one escape the folder
    if root not in path.parents:
        raise DocumentStoreError(f"Invalid document key: {key}")
    return path


def _s3():
    return boto3.client(
        "s3",
        aws_access_key_id     = settings.AWS_ACCESS_KEY_ID,
        aws_secret_access_key = settings.AWS_SECRET_ACCESS_KEY,
        region_name           = settings.AWS_REGION,
    )


def put(key: str, data: bytes) -> None:
    if settings.document_storage == "local":
        path = _local_path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        except OSError as exc:
            raise DocumentStoreError(str(exc)) from exc
        return
    try:
        _s3().put_object(
            Bucket               = settings.DOCUMENTS_BUCKET,
            Key                  = key,
            Body                 = data,
            ContentType          = "application/octet-stream",
            ServerSideEncryption = "AES256",
        )
    except (BotoCoreError, ClientError) as exc:
        raise DocumentStoreError(str(exc)) from exc


def get(key: str) -> bytes:
    if settings.document_storage == "local":
        try:
            return _local_path(key).read_bytes()
        except OSError as exc:
            raise DocumentStoreError(str(exc)) from exc
    try:
        return _s3().get_object(Bucket=settings.DOCUMENTS_BUCKET, Key=key)["Body"].read()
    except (BotoCoreError, ClientError) as exc:
        raise DocumentStoreError(str(exc)) from exc
